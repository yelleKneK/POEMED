}

## ---- 2. Rd markup inside math (parsed, not grepped) --------------------------------
math_markup <- "\\\\(code|emph|link|strong|pkg|bold|var|samp|file|env|dQuote|sQuote|href|url)\\{"
math_nodes <- function(x) {
  tag <- attr(x, "Rd_tag")
  here <- if (!is.null(tag) && tag %in% c("\\eqn", "\\deqn")) paste(unlist(x), collapse = "") else character()
  below <- if (is.list(x)) unlist(lapply(x, math_nodes)) else character()
  c(here, below)
}
