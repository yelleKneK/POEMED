## ---- 11. Nothing in the tarball or the history that should not be ------------------
# The authorship residue and the conventions file's name are assembled from
# character codes, so this file never carries the strings it sweeps for.
# The sweep covers every ref that can reach GitHub. A local branch named
# *-private (the pre-release development history kept after the public
# branch was rebuilt as a single parentless commit, the route SIEVER and
# DMAR took) is excluded, and only while it has no upstream: the moment
# such a branch is tracked remotely it is back in the sweep.
refs <- git("for-each-ref", shQuote("--format=%(refname)"), "refs/heads", "refs/remotes", "refs/tags")
private_refs <- grep("^refs/heads/.*-private$", refs, value = TRUE)
tracked_private <- private_refs[vapply(private_refs, function(b)
  length(git("rev-parse", "--abbrev-ref", paste0(sub("^refs/heads/", "", b), "@{upstream}"))) > 0L, logical(1))]
# The gh-pages branch holds the built pkgdown site, written by the deploy
