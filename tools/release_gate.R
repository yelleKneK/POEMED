## ---- 5a. The letter to CRAN: placeholders still to be filled -------------------------
# cran-comments.md is completed after the win-builder runs, so an unfilled
# placeholder never fails the gate; the count, and the lines that carry
# one, go in the final line and the record so that no letter leaves with
# one. The marker is assembled here rather than written out, so a search of
# the repository for it finds the letter alone. The counter is shown a
# known-bad line first and must count it.
fill_marker <- paste0(strrep("[", 2L), "FILL")
count_fill <- function(lines) sum(lengths(regmatches(lines, gregexpr(fill_marker, lines, fixed = TRUE))))
fill_control <- identical(count_fill(sprintf("a %s: x]] b %s: y]]", fill_marker, fill_marker)), 2L) &&
  identical(count_fill("a filled line"), 0L)
gate("letter placeholder counter flags its known-bad case", fill_control)
letter <- if (file.exists("cran-comments.md")) readLines("cran-comments.md", warn = FALSE) else NULL
letter_fill <- if (is.null(letter)) NA_integer_ else count_fill(letter)
letter_lines <- if (is.null(letter)) integer() else grep(fill_marker, letter, fixed = TRUE)
letter_summary <- if (is.null(letter)) {
  "letter to CRAN: cran-comments.md not found"
} else if (letter_fill == 0L) {
  "letter to CRAN: no unfilled placeholders"
} else {
  sprintf("letter to CRAN: %d unfilled %s]] placeholder%s (cran-comments.md line%s %s)", letter_fill,
          fill_marker, if (letter_fill == 1L) "" else "s", if (length(letter_lines) == 1L) "" else "s",
          paste(letter_lines, collapse = ", "))
}
cat("        ", letter_summary, "\n", sep = "")

