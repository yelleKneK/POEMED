# The results live in a small environment, so no function here assigns
# outside its own frame.
state <- new.env(parent = emptyenv())
state$results <- list()
record_result <- function(name, status, detail) {
  cat(sprintf("[%s] %s\n", status, name))
  for (d in detail) cat("       ", d, "\n", sep = "")
  state$results[[length(state$results) + 1L]] <- list(name = name, status = status, detail = detail)
}
gate <- function(name, ok, detail = character()) {
  record_result(name, if (isTRUE(ok)) "PASS" else "FAIL", detail)
  invisible(isTRUE(ok))
}
# A step that did not run: recorded and listed as skipped, with the reason.
gate_skip <- function(name, reason) {
  record_result(name, "SKIP", reason)
  invisible(NA)
}
statuses <- function() vapply(state$results, `[[`, "", "status")
skipped_names <- function() vapply(Filter(function(r) r$status == "SKIP", state$results), `[[`, "", "name")
skip_summary <- function() {
  sk <- skipped_names()
  if (!length(sk)) "none skipped" else sprintf("%d skipped [%s]", length(sk), paste(sk, collapse = "; "))
}
run <- function(cmd, args, log) {
  status <- system2(cmd, args, stdout = log, stderr = log)
  list(status = status, lines = readLines(log, warn = FALSE))
}
# A git that actually runs (see tools/release_checks.R: /usr/local/bin/git
# here is a stale Intel binary that exits 126 and would make every git gate
# pass on empty output).
git_bin <- local({
  cands <- unique(c(Sys.which("git"), "/usr/bin/git", "/opt/homebrew/bin/git"))
  cands <- cands[nzchar(cands) & file.exists(cands)]
  ok <- vapply(cands, function(g) identical(suppressWarnings(
    tryCatch(system2(g, "--version", stdout = FALSE, stderr = FALSE), error = function(e) 1L)), 0L), logical(1))
  if (any(ok)) cands[ok][1] else NA_character_
})
git <- function(...) suppressWarnings(system2(git_bin, c(...), stdout = TRUE, stderr = FALSE))
