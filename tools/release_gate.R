# The release gate for POEMED: the check CRAN runs, run here first, in full.
#
# No tarball leaves this machine without a full-mode run of this script
# printing ALL GATES PASSED and writing its record (with the tarball's
# sha256) to the Quality Control folder. It is POEMED's copy of the portfolio
# release gate (Kelley_R_Package_QC_Master.md, "Release gate", decided
# 2026-08-21, after DMAR's CRAN returns proved that checks run with a step
# disabled let detectable defects through). Nothing here is optional and
# nothing is skipped for speed in full mode.
#
# Usage, from the package root:
#   caffeinate -i Rscript tools/release_gate.R            # full mode, before any tarball
#   Rscript tools/release_gate.R --quick                  # after any documentation edit
#
# Full mode refuses to start on macOS without a caffeinate assertion,
# because the timing gates read wall-clock times from the check and a
# machine that sleeps mid-run records minutes of elapsed time against
# seconds of CPU. Do not edit this file while a run is in progress: R
# reads it incrementally.
#
# Quick mode runs the static invariants (tools/release_checks.R),
# regenerates the Rd files and refuses stale documentation, renders the
# whole PDF manual through LaTeX, and runs the spelling and pkgdown gates.
# Every gate prints PASS, FAIL, or SKIP. A step that did not run (a check
# R CMD check itself skipped, or a static check whose input is absent from
# the tree) is recorded as SKIP with its reason, never as PASS; it does not
# fail the gate, and the final line and the record list it by name. Both
# modes also read the letter to CRAN (cran-comments.md) and report how many
# placeholders are still to be filled; that count never fails the gate,
# because the letter is completed after the win-builder runs.
# Full mode adds: a version and date that can be released, a clean working
# tree, the tarball built from the committed tree outside Dropbox,
# R CMD check --as-cran with both manuals and the remote URL checks, the
# example and whole-check time budgets, the complete local test suite
# (the article's pinned values included), the live oracle against the
# reference implementation that produced the article's numbers, and a
# sweep of the tarball and git history for anything that should not be in
# them. tools/ is excluded from the tarball by .Rbuildignore.

