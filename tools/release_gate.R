allowed_note <- function(h) grepl("CRAN incoming feasibility", h) ||
  (grepl("HTML version of manual", h) && any(grepl("recent enough HTML Tidy", log)))
bad_notes <- note_heads[!vapply(note_heads, allowed_note, logical(1))]
# The feasibility block may say only what a new submission says: "New
# submission". Anything else in it fails the gate, and no ERROR of any
# kind is allowed (the standard's Section 5.3, rule 4).
fi <- grep("CRAN incoming feasibility", log)[1]
feas <- if (is.na(fi)) character() else {
  k <- fi + 1L; out <- character()
  while (k <= length(log) && !grepl("^\\* ", log[k])) { out <- c(out, log[k]); k <- k + 1L }
  out
}
feas_extra <- grep("invalid file URIs|Non-FOSS|Insufficient package version|Size of tarball|Days since last update|misspelled|Found the following|invalid URLs|The Title field|The Description field|Conflicting package names",
                   feas, value = TRUE)
# URL problems: take the whole block, re-probe any 5xx (a gateway timeout at
# the checker's moment is environmental); only a reproducible problem fails,
# and every flagged URL is recorded either way.
url_start <- grep("invalid URLs", log)
url_bad <- character()
if (length(url_start)) {
  k <- url_start[1] + 1L; url_block <- character()
  while (k <= length(log) && grepl("^\\s", log[k])) { url_block <- c(url_block, trimws(log[k])); k <- k + 1L }
  urls <- sub("^URL: ", "", grep("^URL: ", url_block, value = TRUE))
  statuses <- sub("^Status: ", "", grep("^Status: ", url_block, value = TRUE))
  for (i in seq_along(urls)) {
    st <- if (i <= length(statuses)) statuses[i] else "?"
    u <- sub(" \\(moved to .*\\)$", "", urls[i])
    if (grepl("^5", st)) {
      code <- tryCatch(system2("curl", c("-s", "-o", "/dev/null", "-w", "%{http_code}", "-L", "--max-time", "20", shQuote(u)), stdout = TRUE), error = function(e) "000")
      if (identical(code, "200")) { cat("        transient ", st, " at check time; re-probe returned 200: ", u, "\n", sep = ""); next }
    }
    url_bad <- c(url_bad, sprintf("%s [%s]", urls[i], st))
  }
}
